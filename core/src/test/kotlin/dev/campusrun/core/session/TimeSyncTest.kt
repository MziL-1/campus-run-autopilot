package dev.campusrun.core.session

import dev.campusrun.core.api.ApiClient
import dev.campusrun.core.config.ProtocolParams
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.OkHttpClient
import okhttp3.Protocol
import okhttp3.Response
import okhttp3.ResponseBody.Companion.toResponseBody
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Test

/**
 * Offline fixtures: `session/gmttime.json` is generated by `tools/gen-vectors.py` from the
 * upstream tree. Each case pins the local clock sample, the server epoch milliseconds and the
 * encrypted `{"r","s","v"}` envelope upstream's `get_server_time` decrypts.
 */
class TimeSyncTest {

    private data class Case(
        val name: String,
        val path: String,
        val localMs: Long,
        val serverMs: Long,
        val params: ProtocolParams,
        val responseBody: String,
    )

    @Test
    fun `serverOffsetMs matches fixture skew`() {
        val cases = fixtureCases()
        assertTrue(cases.size >= 2, "expected at least 2 gmt fixtures, got ${cases.size}")
        assertTrue(cases.any { it.serverMs > it.localMs }, "fixture must cover a server-ahead skew")
        assertTrue(cases.any { it.serverMs < it.localMs }, "fixture must cover a server-behind skew")
        cases.forEach { case ->
            val requestedPaths = mutableListOf<String>()
            val api = apiServing(case.responseBody, case.params, requestedPaths = requestedPaths)
            val timeSync = TimeSync(api, nowMs = { case.localMs })
            assertEquals(case.serverMs - case.localMs, timeSync.serverOffsetMs(), "offset ${case.name}")
            assertEquals(listOf(case.path), requestedPaths, "request path ${case.name}")
        }
    }

    @Test
    fun `serverOffsetMs falls back to zero when the response is not a server time`() {
        // Upstream get_server_time: `else ServerTime.from_api(t0, t0)` -> offset 0.
        val api = apiServing("""{"error":10001,"message":"denied"}""", fixtureCases().first().params)
        assertEquals(0L, TimeSync(api, nowMs = { 1_750_123_454_000L }).serverOffsetMs())
    }

    @Test
    fun `serverOffsetMs falls back to zero on transport errors`() {
        val api = apiServing("""{"message":"boom"}""", fixtureCases().first().params, status = 500)
        assertEquals(0L, TimeSync(api, nowMs = { 1_750_123_454_000L }).serverOffsetMs())
    }

    private fun apiServing(
        body: String,
        params: ProtocolParams,
        status: Int = 200,
        requestedPaths: MutableList<String> = mutableListOf(),
    ): ApiClient {
        val client = OkHttpClient.Builder()
            .addInterceptor { chain ->
                requestedPaths += chain.request().url.encodedPath
                Response.Builder()
                    .request(chain.request())
                    .protocol(Protocol.HTTP_1_1)
                    .code(status)
                    .message(if (status == 200) "OK" else "Server Error")
                    .body(body.toResponseBody("application/json".toMediaType()))
                    .build()
            }
            .build()
        return ApiClient(params = params, client = client)
    }

    private fun fixtureCases(): List<Case> {
        val text = checkNotNull(javaClass.classLoader.getResourceAsStream("session/gmttime.json")) {
            "missing session/gmttime.json (run tools/gen-vectors.py)"
        }.use { it.readBytes().toString(Charsets.UTF_8) }
        return Json.parseToJsonElement(text).jsonObject.getValue("cases").jsonArray.map { element ->
            val obj = element.jsonObject
            Case(
                name = obj.string("name"),
                path = obj.string("path"),
                localMs = obj.string("localMs").toLong(),
                serverMs = obj.string("serverMs").toLong(),
                params = ProtocolParams(
                    aesKey = obj.string("aesKeyHex").hexToBytes(),
                    kdfSalt = obj.string("kdfSaltHex").hexToBytes(),
                    rsaPublicKey = obj.string("rsaPublicKey"),
                    endpointBase = "https://offline.invalid",
                    signSalt = "2slhe02lsfiwowlcixisla_sls-_slaor",
                    versionTag = 1,
                ),
                responseBody = obj.string("responseBody"),
            )
        }
    }

    private fun JsonObject.string(key: String): String = getValue(key).jsonPrimitive.content

    private fun String.hexToBytes(): ByteArray =
        ByteArray(length / 2) { substring(it * 2, it * 2 + 2).toInt(16).toByte() }
}
